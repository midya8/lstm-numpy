"""Two synthetic corpora with checkable structure.

sentences: small English-like strings from a context-free grammar, so a
model can only do well by learning word shapes and agreement.

parens: arithmetic expressions over single digits, + and *, generated by
a recursive rule with bounded depth. Every training string is balanced,
which gives sampling a measurable target: a balanced-paren rate of 1.0.
"""

import numpy as np

ADJ = ["big", "small", "old", "new", "quiet", "bright", "cold", "warm"]
NOUN_S = ["cat", "dog", "bird", "fox", "owl", "fish", "horse", "goat"]
VERB_S = ["runs", "sleeps", "eats", "flies", "jumps", "hides", "sings"]
VERB_P = ["run", "sleep", "eat", "fly", "jump", "hide", "sing"]
PREP = ["near", "under", "over", "beside", "behind", "past"]


def make_sentence(rng):
    n1 = NOUN_S[rng.integers(len(NOUN_S))]
    plural = rng.random() < 0.5
    subj = n1 + ("s" if plural else "")
    verb = (VERB_P if plural else VERB_S)[rng.integers(len(VERB_S))]
    words = ["the", ADJ[rng.integers(len(ADJ))], subj, verb]
    if rng.random() < 0.6:
        words += [PREP[rng.integers(len(PREP))], "the",
                  ADJ[rng.integers(len(ADJ))],
                  NOUN_S[rng.integers(len(NOUN_S))] + ("s" if rng.random() < 0.5 else "")]
    words.append(".")
    return " ".join(words)


def paren_expr(rng, depth_left):
    if depth_left == 0 or rng.random() < 0.35:
        return str(rng.integers(10))
    op = ["+", "*"][rng.integers(2)]
    a = paren_expr(rng, depth_left - 1)
    b = paren_expr(rng, depth_left - 1)
    return "(" + a + op + b + ")"


def build(seed=5):
    rng = np.random.default_rng(seed)
    sents = [make_sentence(rng) for _ in range(1500)]
    exprs = [paren_expr(rng, int(rng.integers(1, 4))) for _ in range(2000)]
    text_a = "\n".join(sents)
    text_b = "\n".join(exprs)
    return {"sentences": text_a, "parens": text_b}
